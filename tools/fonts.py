#!/usr/bin/env python3
"""
Makes src/font_data.inc, the window's font, from
third_party/fonts/ChicagoFLF.ttf: the TrueType file LZSS-packed as
lzss_decode() reads it (src/font.c unpacks it). The output is committed,
so building Blue needs nothing more.

  tools/fonts.py
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from icons import ROOT, c_bytes, lzss_decode, lzss_encode  # noqa: E402

FONT = os.path.join('third_party', 'fonts', 'ChicagoFLF.ttf')


def em_scale(ttf):
    """
    Its em over its height from ascent to descent, what Dear ImGui sizes
    fonts by: what size n is scaled by to have an em of n pixels
    """
    tables = {}
    for k in range(struct.unpack('>H', ttf[4:6])[0]):
        tag, _, at, _ = struct.unpack('>4sIII', ttf[12 + 16 * k:28 + 16 * k])
        tables[tag] = at
    units = struct.unpack('>H', ttf[tables[b'head'] + 18:tables[b'head'] + 20])[0]
    ascent, descent = struct.unpack('>hh', ttf[tables[b'hhea'] + 4:tables[b'hhea'] + 8])
    return (ascent - descent) / units


def main():
    with open(os.path.join(ROOT, FONT), 'rb') as f:
        ttf = f.read()
    packed = lzss_encode(ttf)
    assert lzss_decode(packed, len(ttf)) == ttf
    out = os.path.join(ROOT, 'src', 'font_data.inc')
    with open(out, 'w') as f:
        f.write(f'/* Generated by tools/fonts.py from {FONT}: not to be edited. */\n')
        f.write('/* ChicagoFLF (Robin Casady; public domain: see third_party/fonts/README), LZSS-packed */\n')
        f.write(f'#define FONT_TTF_SIZE {len(ttf)}u\n')
        f.write(f'#define FONT_EM_SCALE {em_scale(ttf):.6g}f\n')
        f.write(c_bytes('font_lzss', packed))
    print(f'fonts: {os.path.relpath(out, ROOT)} ({len(packed)} bytes for {len(ttf)})')


if __name__ == '__main__':
    main()
